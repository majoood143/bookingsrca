<?php

namespace App\Filament\Resources\PosOrderResource\RelationManagers;

use Filament\Resources\RelationManagers\RelationManager;
use Filament\Schemas\Schema;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Table;

class PaymentsRelationManager extends RelationManager
{
    protected static string $relationship = 'payments';

    public static function getTitle($ownerRecord, string $pageClass): string
    {
        return __('Payments');
    }

    public function form(Schema $schema): Schema
    {
        return $schema->components([]);
    }

    public function table(Table $table): Table
    {
        return $table
            ->columns([
                TextColumn::make('method')->label(__('Method'))->badge(),
                TextColumn::make('amount')->label(__('Amount')),
                TextColumn::make('reference')->label(__('Reference'))->placeholder('—'),
            ]);
    }
}
